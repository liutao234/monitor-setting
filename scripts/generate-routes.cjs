// Build a local, synchronous route bundle from the existing standalone pages.
// Keeping their HTML/catalogs as source avoids parallel UI implementations.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.resolve(__dirname, '..');
const read = file => fs.readFileSync(path.join(root, file), 'utf8');
const selectors = { basic: 'div class="basic-layout"', 'multi-display': 'div class="multi-layout"', color: 'section class="panel color-panel"' };
const routes = {};
for (const [route, marker] of Object.entries(selectors)) {
  const html = read(route + '/index.html');
  const start = html.indexOf('<' + marker);
  const end = html.indexOf('<footer class="page-footer"', start);
  if (start < 0 || end < 0) throw new Error(`Cannot extract ${route} content`);
  routes[route] = html.slice(start, end).trim();
}
const basicHtml = read('basic/index.html');
const symbols = basicHtml.match(/<svg width="0"[\s\S]*?<\/svg>/)?.[0];
if (!symbols) throw new Error('Basic monitor symbol definitions not found');
const colorCss = [...read('color/index.html').matchAll(/<style>([\s\S]*?)<\/style>/g)].map(match => match[1]).join('\n');
const css = [read('basic/styles.css'), read('multi-display/arrangement.css'), colorCss].join('\n');
const catalogs = {};
const register = catalog => {
  for (const [locale, messages] of Object.entries(catalog)) Object.assign(catalogs[locale] ??= {}, messages);
};
for (const sources of [['basic/settings.js'], ['color/color.js'], ['multi-display/translations.js', 'multi-display/arrangement.js']]) {
  const context = { window: { chrome: { webview: {} }, monitorI18n: { register, t: key => key } } };
  vm.runInNewContext(sources.map(read).join('\n'), context, { timeout: 1000 });
}
const output = `// Generated by scripts/generate-routes.cjs. Edit the source pages/catalogs instead.\n(() => {\n  if (!window.chrome?.webview) return;\n  window.desktopRoutes = ${JSON.stringify({ routes, symbols, catalogs })};\n  const styles = document.createElement('style');\n  styles.dataset.desktopRoutes = '';\n  styles.textContent = ${JSON.stringify(css)};\n  const glass = document.querySelector('link[href$="glass.css"]');\n  if (glass) glass.before(styles); else document.head.append(styles);\n})();\n`;
fs.writeFileSync(path.join(root, 'desktop-routes.js'), output);
console.log(`Generated desktop-routes.js (${Buffer.byteLength(output)} bytes)`);
